"""Confirmed Genshin character presets and their default outfits."""
from __future__ import annotations

from character_preset_separation import separate_character_outfit


def _preset(
    preset_id: str,
    name: str,
    work: str,
    appearance_tags: list[str],
    outfit_id: str,
    outfit_name: str,
    outfit_translation: str,
    outfit_tags: list[str],
) -> dict:
    appearance_tags, outfit_tags = separate_character_outfit(
        appearance_tags,
        outfit_tags,
        work=work,
    )
    return {
        "preset_id": preset_id,
        "name": name,
        "work": work,
        "category": "角色",
        "appearance_tags": appearance_tags,
        "outfit_id": outfit_id,
        "outfit_name": outfit_name,
        "outfit_translation": outfit_translation,
        "outfit_tags": outfit_tags,
    }


