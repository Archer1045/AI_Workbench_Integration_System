PEOPLE_EXCLUSION_PATTERN = re.compile(
    r"(?:,?\s*(?:and\s+)?)?"
    r"(?:no\s+(?:visible\s+)?(?:people|humans?|characters?)"
    r"|without\s+(?:visible\s+)?people"
    r"|people[-\s]+free)\b",
    re.IGNORECASE,
)


def strip_people_exclusions(prompt: str) -> str:
    """Remove explicit empty-scene constraints while preserving the scene prose."""
    text = PEOPLE_EXCLUSION_PATTERN.sub("", str(prompt or ""))
    text = re.sub(r"\s+,", ",", text)
    text = re.sub(r",\s*,+", ", ", text)
    text = re.sub(r"\s{2,}", " ", text)
    return text.strip(" ,")


def scene_prompt_variants(prompt: str) -> dict[str, str | None]:
    """Build occupied and empty prompt variants without changing the legacy prompt."""
    empty_scene_prompt = str(prompt or "").strip()
    has_people_exclusion = bool(PEOPLE_EXCLUSION_PATTERN.search(empty_scene_prompt))
    occupied_scene_prompt = strip_people_exclusions(empty_scene_prompt)
    if not has_people_exclusion:
        empty_scene_prompt = f"{occupied_scene_prompt}, no people"
    return {
        "people_policy": "empty" if has_people_exclusion else "occupied",
        "empty_scene_prompt": empty_scene_prompt,
        "occupied_scene_prompt": occupied_scene_prompt,
    }


def _scene(
    preset_id: str,
    category: str,
    label: str,
    translation: str,
    tags: list[str],
    *,
    rating: str = "R18",
    intensity: str = "强化",
    setting: str,
    equipment: list[str],
    camera: str,
    lighting: str,
    people: str = "双人",
    orientation: str = "男女",
    role_slots: list[str] | None = None,
    contact_points: list[str] | None = None,
    body_separation: bool = True,
    conflicts: list[str] | None = None,
    draw_prompt: str,
) -> dict:
    return {
        "schema_version": 2,
        "id": preset_id,
        "category": category,
        "label": label,
        "translation": translation,
        "tags": tags,
        "rating": rating,
        "intensity": intensity,
        "source": "builtin",
        "people": people,
        "orientation": orientation,
        "role_slots": role_slots or ["角色A", "角色B"],
        "body_separation": body_separation,
        "contact_points": contact_points or [],
        "setting": setting,
        "equipment": equipment,
        "camera": camera,
        "lighting": lighting,
        "conflicts": conflicts or [],
        "draw_prompt": draw_prompt,
        **scene_prompt_variants(draw_prompt),
        "has_image": False,
        "image": None,
    }


