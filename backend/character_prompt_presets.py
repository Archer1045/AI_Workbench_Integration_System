    for item in base_presets:
        preset_id = str(item["preset_id"])
        replacement = CHARACTER_PROMPT_PRESETS_BY_ID.get(preset_id, item)
        items.append(replacement)
        seen.add(preset_id)
    items.extend(
        item for item in CHARACTER_PROMPT_PRESETS
        if item["preset_id"] not in seen
    )
    return tuple(items)
